"""The user the library PCs' connectors post as (scripts/library_connector/tanmya_connector.py), with the least it
needs: the role Library Connector, which library_sync.sync.receive accepts, and nothing else (no desk, no reports).

    bench --site <site> execute imed_erp.setup.setup_library_connector.run

Idempotent. It prints no secret: the API key and secret are generated by the owner on the user's form (User >
API Access > Generate Keys, shown once) and typed into each PC's config.json. One user serves both libraries; each
PC's config names its library (pc1, ...), which is what keeps their documents apart.
"""

import frappe

ROLE = "Library Connector"
USER = "library-connector@imed.local"


def run():
	if not frappe.db.exists("Role", ROLE):
		frappe.get_doc({"doctype": "Role", "role_name": ROLE, "desk_access": 0, "disabled": 0}).insert(ignore_permissions=True)
	if not frappe.db.exists("User", USER):
		user = frappe.get_doc(
			{
				"doctype": "User",
				"email": USER,
				"first_name": "Library Connector",
				"user_type": "System User",
				"send_welcome_email": 0,
				"enabled": 1,
				"roles": [{"role": ROLE}],
			}
		)
		user.flags.ignore_permissions = True
		user.insert(ignore_permissions=True)
	else:
		user = frappe.get_doc("User", USER)
		if not any(r.role == ROLE for r in user.roles):
			user.append("roles", {"role": ROLE})
			user.save(ignore_permissions=True)
	frappe.db.commit()
	return {"role": ROLE, "user": USER, "keys": "generate on the user's form (API Access), never printed here"}
